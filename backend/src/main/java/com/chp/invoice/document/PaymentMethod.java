package com.chp.invoice.document;

/** ช่องทางการชำระของใบแจ้งหนี้ / ใบเสร็จรับเงิน (ไม่ระบุก็ได้ = null) */
public enum PaymentMethod {
    /** เงินสด */
    CASH,
    /** เช็ค — กรอกธนาคาร สาขา เลขที่เช็ค วันที่ประกอบ */
    CHEQUE,
    /** โอนเงิน — เอกสารแสดงบัญชีธนาคารที่เลือกไว้ในเมนูบัญชีธนาคาร (ไม่มีช่องกรอกเพิ่ม) */
    TRANSFER
}
